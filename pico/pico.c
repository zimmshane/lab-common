void send_sprite(int rotation) {
  for (int dst = 0; dst < SPRITE_SIZE; dst++) {
    int dst_row = dst / SPRITE_W;
    int dst_col = dst % SPRITE_W;

    int src_row, src_col;
    switch (rotation) {
    default:
    case 0: // 0
      src_row = dst_row;
      src_col = dst_col;
      break;
    case 1: // 90 CW
      src_row = (SPRITE_H - 1) - dst_col;
      src_col = dst_row;
      break;
    case 2: // 180 CW
      src_row = (SPRITE_H - 1) - dst_row;
      src_col = (SPRITE_W - 1) - dst_col;
      break;
    case 3: // 270 CW = 90 CCW
      src_row = dst_col;
      src_col = (SPRITE_W - 1) - dst_row;
      break;
    }

    uint16_t pixel = mario_pattern[src_row * SPRITE_W + src_col];
    uint8_t addr = (uint8_t)dst;

    uint8_t tx[3];
    tx[0] = addr;
    tx[1] = pixel & 0xFF;        // LSB
    tx[2] = (pixel >> 8) & 0xFF; // MSB

    gpio_put(PIN_CS_FPGA, 0);
    spi_write_blocking(SPI_PORT, tx, 3);
    gpio_put(PIN_CS_FPGA, 1);

    sleep_us(100);
  }
}

int main() {
  stdio_init_all();
  init_spi();

  int rotation = 0;

  while (true) {
    send_sprite(rotation);
    rotation = (rotation + 1) % 4;
    sleep_ms(1000);
  }
}
